"""
report.py — レポート生成 / Report generation

Markdown・JSON・コンソール表示の3形式で結果を出力します。
GitHubのREADMEやポートフォリオにそのまま貼れるMarkdownです。

Outputs results as Markdown (portfolio-ready), JSON, and console text.
"""

import json
import os
from datetime import datetime, timezone

SEVERITY_ORDER = {"High": 0, "Medium": 1, "Low": 2, "Info": 3}
SEVERITY_EMOJI = {"High": "🔴", "Medium": "🟠", "Low": "🟡", "Info": "🔵"}


def _sort(findings):
    return sorted(findings, key=lambda f: SEVERITY_ORDER.get(f.severity, 9))


def render_console(findings, learn_mode=False):
    """コンソールに分かりやすく表示 / Pretty console output."""
    if not findings:
        print("\n✅ 問題は検出されませんでした！ Great job!\n")
        return
    print(f"\n=== 検出結果 / Findings: {len(findings)} 件 ===\n")
    for f in _sort(findings):
        emoji = SEVERITY_EMOJI.get(f.severity, "⚪")
        print(f"{emoji} [{f.severity}] {f.name_ja} / {f.name_en}")
        print(f"   なぜ危険？ / Why: {f.why_dangerous_ja}")
        print(f"   確認方法 / How: {f.how_detected_ja}")
        print(f"   修正方法 / Fix: {f.how_to_fix_ja}")
        print(f"   参考 / Ref: {f.owasp}")
        if learn_mode:
            # 学習モードでは証拠と「次の一歩」も表示
            print(f"   証拠 / Evidence: {f.evidence}")
            print(f"   📘 次の一歩: docs/vulnerabilities/ の解説を読み、修正 → 再スキャンしてみよう！")
        print()


def to_json_dict(target, findings):
    """JSON出力用のdict / Serializable result dict."""
    return {
        "tool": "CyberLearn Scanner",
        "target": target,
        "scanned_at": datetime.now(timezone.utc).isoformat(),
        "summary": {
            "total": len(findings),
            "by_severity": {
                s: sum(1 for f in findings if f.severity == s)
                for s in ("High", "Medium", "Low", "Info")
            },
        },
        "findings": [
            {
                "id": f.id,
                "severity": f.severity,
                "name_ja": f.name_ja,
                "name_en": f.name_en,
                "owasp": f.owasp,
                "why_dangerous_ja": f.why_dangerous_ja,
                "how_detected_ja": f.how_detected_ja,
                "how_to_fix_ja": f.how_to_fix_ja,
                "evidence": f.evidence,
            }
            for f in _sort(findings)
        ],
    }


def render_markdown(target, findings):
    """ポートフォリオ向けMarkdown / Portfolio-ready Markdown report."""
    d = to_json_dict(target, findings)
    lines = [
        "# CyberLearn Scanner レポート / Scan Report",
        "",
        f"- **実行日時 / Date (UTC):** {d['scanned_at']}",
        f"- **対象 / Target:** `{target}`（自分のローカル練習環境 / my local practice app）",
        f"- **検出数 / Total findings:** {d['summary']['total']} "
        f"(🔴 {d['summary']['by_severity']['High']} "
        f"🟠 {d['summary']['by_severity']['Medium']} "
        f"🟡 {d['summary']['by_severity']['Low']} "
        f"🔵 {d['summary']['by_severity']['Info']})",
        "",
        "> 本レポートは教育目的で、自分のローカル環境に対してのみ実行されました。",
        "> Educational report generated against my own local environment only.",
        "",
        "| 重要度 | 脆弱性 | OWASP |",
        "|---|---|---|",
    ]
    for f in _sort(findings):
        emoji = SEVERITY_EMOJI.get(f.severity, "⚪")
        lines.append(f"| {emoji} {f.severity} | {f.name_ja} | {f.owasp.split('—')[0].strip()} |")
    lines += ["", "---", ""]
    for f in _sort(findings):
        emoji = SEVERITY_EMOJI.get(f.severity, "⚪")
        lines += [
            f"## {emoji} {f.name_ja} / {f.name_en}",
            "",
            f"- **重要度 / Severity:** {f.severity}",
            f"- **影響（なぜ危険か） / Impact:** {f.why_dangerous_ja}",
            f"- **原因・確認方法 / How detected:** {f.how_detected_ja}",
            f"- **証拠 / Evidence:** `{f.evidence}`",
            f"- **修正方法 / Fix:** {f.how_to_fix_ja}",
            f"- **再発防止 / Prevention:** 修正後に再スキャンし、CI等で設定を継続確認する。",
            f"- **参考 / Reference:** {f.owasp}",
            "",
        ]
    lines += [
        "---",
        "*Generated by CyberLearn Scanner — 学習は「攻撃」より「防御・修正・説明力」を重視しています。*",
    ]
    return "\n".join(lines)


def save_reports(target, findings, report_path=None, json_path=None):
    """MarkdownとJSONをファイルに保存 / Save Markdown and JSON reports."""
    os.makedirs("reports", exist_ok=True)
    stamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    report_path = report_path or f"reports/report_{stamp}.md"
    json_path = json_path or f"reports/scan_{stamp}.json"
    with open(report_path, "w", encoding="utf-8") as f:
        f.write(render_markdown(target, findings))
    with open(json_path, "w", encoding="utf-8") as f:
        json.dump(to_json_dict(target, findings), f, ensure_ascii=False, indent=2)
    return report_path, json_path
